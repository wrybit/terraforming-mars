#!/usr/bin/env python3
# Builds the web variants of the app background (assets/background/milky-way-*.avif/.webp)
# from the ESO original assets/background/eso0932a.jpg (6000x3000, 6.4 MB).
#
# Why pre-rendered and checked in instead of resized on demand: a fixed set of widths covers every
# viewport within a few percent, the browser picks the right file itself via <picture>/srcset
# (AppBackground.vue), and the server never has to resize anything.
#
# Two crops:
#   landscape – the whole 2:1 panorama
#   portrait  – a 1:2 strip from the middle (galactic centre), for phones held upright; the band
#               stays horizontal as in the original
#
# The original is private (lab repo, see scripts/lab-setup.sh); only the variants are public.
# Change widths or quality here, run
#   python3 scripts/make-backgrounds.py
# and commit the changed files. Never edit the variants by hand.
import os
from PIL import Image

FOLDER = 'assets/background'
SOURCE = os.path.join(FOLDER, 'eso0932a.jpg')
NAME = 'milky-way'

# Widths in image pixels. Portrait goes up to the full height of the original (1500 = 1:2 of 3000),
# enough for phones with 3x pixels.
WIDTHS = {
    'landscape': [960, 1280, 1920, 2560, 3840],
    'portrait': [540, 810, 1080, 1500],
}
# Generated list of the variants for AppBackground.vue – the client never guesses file names
VARIANTS_FILE = 'src/client/components/appBackgroundVariants.ts'
# High quality on purpose: star fields fall apart into blocky mush quickly at low settings,
# and the background has to look good, not be as small as possible
# Order = preference; the last format is the fallback for browsers without AVIF/WebP
QUALITY = {'avif': 72, 'webp': 88, 'jpg': 88}
# Extra save options per format (JPEG: progressive, so it appears early on slow connections)
OPTIONS = {'jpg': {'progressive': True, 'optimize': True}}
# Only the darkest sensor grain in the black sky becomes pure black (saves bytes, invisible)
BLACK_POINT = 6


def crop(original: Image.Image, orientation: str) -> Image.Image:
    if orientation == 'landscape':
        return original
    # Middle strip in 1:2 over the full height (1500x3000): the Milky Way stays horizontal,
    # the phone shows the galactic centre instead of a thin band squeezed by cover
    width, height = original.size
    strip = height // 2
    left = (width - strip) // 2
    return original.crop((left, 0, left + strip, height))


def main() -> None:
    original = Image.open(SOURCE).convert('RGB')
    original = original.point(lambda value: max(0, value - BLACK_POINT) * 255 // (255 - BLACK_POINT))
    for orientation, widths in WIDTHS.items():
        cropped = crop(original, orientation)
        for width in widths:
            height = round(cropped.height * width / cropped.width)
            resized = cropped.resize((width, height), Image.LANCZOS)
            for extension, quality in QUALITY.items():
                target = os.path.join(FOLDER, f'{NAME}-{orientation}-{width}.{extension}')
                resized.save(target, quality=quality, **OPTIONS.get(extension, {}))
                print(f'{target}: {os.path.getsize(target) // 1024} KB')
    write_variants_file()


def write_variants_file() -> None:
    lines = [
        '// Generated by scripts/make-backgrounds.py – do not edit by hand, change the script and run it again.',
        f"export const BACKGROUND_PATH = '{FOLDER}/{NAME}';",
        f'export const BACKGROUND_FORMATS = {list(QUALITY)!r} as const;'.replace('"', "'"),
        'export const BACKGROUND_WIDTHS = {',
        *[f'  {orientation}: {widths!r},' for orientation, widths in WIDTHS.items()],
        '} as const;',
        '',
    ]
    with open(VARIANTS_FILE, 'w') as file:
        file.write('\n'.join(lines))


if __name__ == '__main__':
    main()
