#!/usr/bin/env python3
# Builds the web variants of the app background, one set per theme (common/theme/Theme.ts):
#   mars – Milky Way, from the ESO original assets/background/mars/eso0932a.jpg (6000x3000, 6.4 MB)
#   dune – night over the dunes, from assets/background/dune/desert-univers.png (7096x3548)
#
# Why pre-rendered and checked in instead of resized on demand: a fixed set of widths covers every
# viewport within a few percent, the browser picks the right file itself via <picture>/srcset
# (AppBackground.vue), and the server never has to resize anything.
#
# Two crops:
#   landscape – the whole 2:1 panorama
#   portrait  – a 1:2 strip from the middle, for phones held upright; the horizon stays horizontal
#
# The originals are private (not in the public repo); only the variants are public.
# Change widths or quality here, run
#   python3 scripts/make-backgrounds.py [theme ...]     (default: every theme whose original is present)
# and commit the changed files. Never edit the variants by hand. The variants file for the client is
# always written for all themes.
import os
import sys
from PIL import Image

FOLDER = 'assets/background'

# Per theme: original, name of the variants, black point (only the darkest sensor grain in the black
# sky becomes pure black – saves bytes, invisible)
BACKGROUNDS = {
    'mars': {'source': 'eso0932a.jpg', 'name': 'milky-way', 'black_point': 6},
    'dune': {'source': 'desert-univers.png', 'name': 'desert-universe', 'black_point': 4},
}

# Widths in image pixels. Portrait goes up to the full height of the original (1500 = 1:2 of 3000),
# enough for phones with 3x pixels.
WIDTHS = {
    'landscape': [960, 1280, 1920, 2560, 3840],
    'portrait': [540, 810, 1080, 1500],
}
# Generated list of the variants for AppBackground.vue – the client never guesses file names
VARIANTS_FILE = 'src/client/components/appBackgroundVariants.ts'
# High quality on purpose: star fields fall apart into blocky mush quickly at low settings,
# and the background has to look good, not be as small as possible
# Order = preference; the last format is the fallback for browsers without AVIF/WebP
QUALITY = {'avif': 72, 'webp': 88, 'jpg': 88}
# Extra save options per format (JPEG: progressive, so it appears early on slow connections)
OPTIONS = {'jpg': {'progressive': True, 'optimize': True}}


def folder(theme: str) -> str:
    return os.path.join(FOLDER, theme)


def crop(original: Image.Image, orientation: str) -> Image.Image:
    if orientation == 'landscape':
        return original
    # Middle strip in 1:2 over the full height: the horizon stays horizontal, the phone shows the
    # middle of the panorama instead of a thin band squeezed by cover
    width, height = original.size
    strip = height // 2
    left = (width - strip) // 2
    return original.crop((left, 0, left + strip, height))


def build(theme: str) -> None:
    background = BACKGROUNDS[theme]
    black = background['black_point']
    original = Image.open(os.path.join(folder(theme), background['source'])).convert('RGB')
    original = original.point(lambda value: max(0, value - black) * 255 // (255 - black))
    for orientation, widths in WIDTHS.items():
        cropped = crop(original, orientation)
        for width in widths:
            height = round(cropped.height * width / cropped.width)
            resized = cropped.resize((width, height), Image.LANCZOS)
            for extension, quality in QUALITY.items():
                target = os.path.join(folder(theme), f"{background['name']}-{orientation}-{width}.{extension}")
                resized.save(target, quality=quality, **OPTIONS.get(extension, {}))
                print(f'{target}: {os.path.getsize(target) // 1024} KB')


def write_variants_file() -> None:
    lines = [
        '// Generated by scripts/make-backgrounds.py – do not edit by hand, change the script and run it again.',
        "import {Theme} from '@/common/theme/Theme';",
        '',
        'export const BACKGROUND_PATHS: Record<Theme, string> = {',
        *[f"  {theme}: '{folder(theme)}/{background['name']}'," for theme, background in BACKGROUNDS.items()],
        '};',
        f'export const BACKGROUND_FORMATS = {list(QUALITY)!r} as const;'.replace('"', "'"),
        'export const BACKGROUND_WIDTHS = {',
        *[f'  {orientation}: {widths!r},' for orientation, widths in WIDTHS.items()],
        '} as const;',
        '',
    ]
    with open(VARIANTS_FILE, 'w') as file:
        file.write('\n'.join(lines))


def main() -> None:
    themes = sys.argv[1:] or [theme for theme, background in BACKGROUNDS.items()
                              if os.path.exists(os.path.join(folder(theme), background['source']))]
    for theme in themes:
        build(theme)
    write_variants_file()


if __name__ == '__main__':
    main()
