// Lists the optional extensions present in src/extensions/ (see src/common/extensions/CommonExtension.ts)
// in src/genfiles/extensions{Common,Server,Client}.ts. Without extensions the lists are empty, so the
// game builds the same with or without them. Run by `npm run make:extensions` (write_extension_registries.ts),
// before anything that imports the registries (make_static_json.ts loads the server settings).
import fs from 'fs';
import path from 'path';

const EXTENSIONS_DIR = path.resolve('src/extensions');

type Part = {
  file: 'extension.common' | 'extension.server' | 'extension.client',
  output: string,
  typeImport: string,
  typeName: string,
  constant: string,
};

const PARTS: ReadonlyArray<Part> = [
  {file: 'extension.common', output: 'extensionsCommon.ts', typeImport: '../common/extensions/CommonExtension', typeName: 'CommonExtension', constant: 'COMMON_EXTENSIONS'},
  {file: 'extension.server', output: 'extensionsServer.ts', typeImport: '../server/extensions/ServerExtension', typeName: 'ServerExtension', constant: 'SERVER_EXTENSIONS'},
  {file: 'extension.client', output: 'extensionsClient.ts', typeImport: '../client/extensions/ClientExtension', typeName: 'ClientExtension', constant: 'CLIENT_EXTENSIONS'},
];

/** Names of the extension folders, sorted, so the generated files do not change between machines */
export function extensionNames(): Array<string> {
  if (!fs.existsSync(EXTENSIONS_DIR)) {
    return [];
  }
  return fs.readdirSync(EXTENSIONS_DIR, {withFileTypes: true})
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

/** src/locales and the locales folder of every extension that has one */
export function localeDirectories(): Array<string> {
  return [
    path.resolve('src/locales'),
    ...extensionNames().map((name) => path.join(EXTENSIONS_DIR, name, 'locales')).filter((dir) => fs.existsSync(dir)),
  ];
}

function identifier(name: string): string {
  return name.replace(/[^A-Za-z0-9]+(.)?/g, (_match, next: string | undefined) => (next ?? '').toUpperCase()) + 'Extension';
}

function registry(part: Part, names: ReadonlyArray<string>): string {
  const present = names.filter((name) => fs.existsSync(path.join(EXTENSIONS_DIR, name, `${part.file}.ts`)));
  return [
    '// Generated by src/tools/make_extensions.ts – do not edit.',
    `import type {${part.typeName}} from '${part.typeImport}';`,
    ...present.map((name) => `import {extension as ${identifier(name)}} from '../extensions/${name}/${part.file}';`),
    '',
    `export const ${part.constant}: ReadonlyArray<${part.typeName}> = [${present.map(identifier).join(', ')}];`,
    '',
  ].join('\n');
}

/**
 * Copies src/extensions/<name>/assets/ to assets/extensions/<name>/, where the server serves it like every
 * other picture (and the Docker image picks it up). Generated: not in git.
 */
export function copyExtensionAssets(assetsDir: string = path.resolve('assets/extensions')): void {
  fs.rmSync(assetsDir, {recursive: true, force: true});
  for (const name of extensionNames()) {
    const source = path.join(EXTENSIONS_DIR, name, 'assets');
    if (fs.existsSync(source)) {
      fs.cpSync(source, path.join(assetsDir, name), {recursive: true});
    }
  }
}

export function writeExtensionRegistries(genfilesDir: string = path.resolve('src/genfiles')): void {
  const names = extensionNames();
  for (const part of PARTS) {
    const file = path.join(genfilesDir, part.output);
    const content = registry(part, names);
    // Unchanged files are not rewritten, so watchers do not rebuild for nothing
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) {
      fs.writeFileSync(file, content);
    }
  }
}
