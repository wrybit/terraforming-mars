// Theme pictures (common/theme/Theme.ts): builds assets/themes/<theme>/theme.css from the game's compiled styles.
// src/themes/<theme>/graphics.json maps game pictures (path below assets/) to theme pictures (path below
// assets/themes/<theme>/). Every rule of build/styles.css that shows one of these pictures gets a copy that only
// applies under html.theme-<theme> and shows the theme picture instead – so new uses of a picture in the game's
// styles are themed automatically. The client loads the file only for games in that theme (client/theme/applyTheme.ts).
import fs from 'fs';
import path from 'path';
import postcss, {AtRule, Container, Declaration, Root, Rule} from 'postcss';

const URL_PATTERN = /url\((['"]?)(?:\.?\/)?assets\/([^'")]+)\1\)/g;

/** The selector, restricted to pages of the theme: html.theme-<theme> in front, or merged into a leading html */
export function themedSelector(selector: string, theme: string): string {
  const trimmed = selector.trim();
  if (/^html(?![\w-])/.test(trimmed)) {
    return trimmed.replace(/^html/, `html.theme-${theme}`);
  }
  if (trimmed.startsWith(':root')) {
    return trimmed.replace(/^:root/, `html.theme-${theme}`);
  }
  return `html.theme-${theme} ${trimmed}`;
}

/** The value with every mapped picture replaced; undefined when it shows none of them */
export function themedValue(value: string, graphics: Record<string, string>): string | undefined {
  let changed = false;
  const result = value.replace(URL_PATTERN, (match, _quote, asset: string) => {
    const replacement = graphics[asset];
    if (replacement === undefined) {
      return match;
    }
    changed = true;
    return `url(${replacement})`;
  });
  return changed ? result : undefined;
}

/** Copy of the parent at-rules (e.g. @media) around a rule, so the themed rule keeps its conditions */
function wrapInParents(rule: Rule, source: Rule): Container {
  let node: Container = rule;
  let parent = source.parent;
  while (parent !== undefined && parent.type === 'atrule') {
    const wrapper = (parent as AtRule).clone({nodes: []});
    wrapper.append(node);
    node = wrapper;
    parent = parent.parent;
  }
  return node;
}

export function themeCss(css: string, theme: string, graphics: Record<string, string>): string {
  const output: Root = postcss.root();
  postcss.parse(css).walkRules((rule) => {
    const declarations: Array<Declaration> = [];
    rule.each((node) => {
      if (node.type !== 'decl') {
        return;
      }
      const value = themedValue(node.value, graphics);
      if (value === undefined) {
        return;
      }
      // Only the picture changes: a "background" shorthand becomes "background-image", so size, position and
      // repeat of the game's rules still apply (a shorthand copy would reset them)
      if (node.prop === 'background') {
        const pictures = value.match(/url\([^)]*\)/g) ?? [];
        declarations.push(postcss.decl({prop: 'background-image', value: pictures.join(', '), important: node.important}));
      } else {
        declarations.push(node.clone({value}));
      }
    });
    if (declarations.length === 0) {
      return;
    }
    const themed = postcss.rule({selectors: rule.selectors.map((selector) => themedSelector(selector, theme))});
    themed.append(...declarations);
    output.append(wrapInParents(themed, rule));
  });
  return `/* Generated by src/tools/themeCss.ts from build/styles.css and src/themes/${theme}/graphics.json – do not edit. */\n` +
    output.toString() + '\n';
}

/** Writes assets/themes/<theme>/theme.css for every theme folder with a graphics.json. */
export function writeThemeCss(stylesFile: string, themesFolder: string, outputFolder: string): void {
  if (!fs.existsSync(themesFolder) || !fs.existsSync(stylesFile)) {
    return;
  }
  const css = fs.readFileSync(stylesFile, 'utf8');
  for (const theme of fs.readdirSync(themesFolder)) {
    const graphicsFile = path.join(themesFolder, theme, 'graphics.json');
    if (!fs.existsSync(graphicsFile)) {
      continue;
    }
    const graphics = JSON.parse(fs.readFileSync(graphicsFile, 'utf8')) as Record<string, string>;
    fs.mkdirSync(path.join(outputFolder, theme), {recursive: true});
    // Hand-written rules for pictures the copies cannot swap (sprites, composed tiles) come last and win
    const extraFile = path.join(themesFolder, theme, 'theme-extra.css');
    const extra = fs.existsSync(extraFile) ? fs.readFileSync(extraFile, 'utf8') : '';
    fs.writeFileSync(path.join(outputFolder, theme, 'theme.css'), themeCss(css, theme, graphics) + extra);
  }
}
